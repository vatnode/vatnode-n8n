/**
 * Bakes the VAT number patterns into the node at build time.
 *
 * A verified community node may not have runtime dependencies, so
 * `eu-vat-rates-data` stays a devDependency and only its patterns end up in the
 * published bundle. Rates themselves are not baked in — they change, and the
 * node reads them live from the public vatnode endpoint.
 */
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { getAllRates } from 'eu-vat-rates-data'

const OUTPUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'nodes', 'Vatnode', 'countries.generated.ts')

// VIES also answers for XI (Northern Ireland), which the dataset does not flag
// as an EU member.
const VIES_EXTRA = new Set(['XI'])

/**
 * EU patterns in the dataset include the country prefix (`^DE\d{9}$`), while
 * some non-EU ones do not (`^\d{9}MVA$` for Norway). The node always matches
 * against the full normalized number, so anchor every pattern to its prefix.
 */
function withCountryPrefix(code, pattern) {
	if (!pattern) return null
	return pattern
		.split('|')
		.map((alternative) => {
			const body = alternative.startsWith('^') ? alternative.slice(1) : alternative
			// Any two leading capitals are already a VAT prefix — Greece uses EL
			// while the dataset keys it under GR, so do not compare with `code`.
			return /^[A-Z]{2}/.test(body) ? `^${body}` : `^${code}${body}`
		})
		.join('|')
}

const countries = Object.entries(getAllRates())
	.map(([code, entry]) => ({
		code,
		name: entry.country,
		pattern: withCountryPrefix(code, entry.pattern),
		viesEligible: Boolean(entry.eu_member) || VIES_EXTRA.has(code),
	}))
	.sort((a, b) => a.code.localeCompare(b.code))

// Greek VAT numbers carry the EL prefix even though the dataset (and the rate
// endpoint) key the country as GR. Expose both so a number pasted from an
// invoice resolves.
const greece = countries.find((country) => country.code === 'GR')
if (greece) {
	countries.push({ ...greece, code: 'EL' })
	countries.sort((a, b) => a.code.localeCompare(b.code))
}

const file = `// Generated by scripts/generate-patterns.mjs — do not edit by hand.
// Source: eu-vat-rates-data (European Commission TEDB).

export interface CountryEntry {
	code: string;
	name: string;
	pattern: string | null;
	viesEligible: boolean;
}

export const COUNTRIES: CountryEntry[] = ${JSON.stringify(countries, null, '\t')};

export const COUNTRY_BY_CODE: Record<string, CountryEntry> = Object.fromEntries(
	COUNTRIES.map((country) => [country.code, country]),
);
`

writeFileSync(OUTPUT, file)
console.log(`Wrote ${countries.length} countries to ${OUTPUT}`)
